export const getHexagramById = (id: number): Hexagram | undefined => {
  return hexagrams.find(h => h.id === id);
};

export const getHexagramByLines = (lines: number[]): Hexagram | undefined => {
  const binary = lines.map(l => l === 1 ? '1' : '0').join('');
  const decimal = parseInt(binary, 2);
  return hexagrams[decimal];
};

export const generateRandomHexagram = (): Hexagram => {
  const lines: number[] = [];
  for (let i = 0; i < 6; i++) {
    lines.push(Math.random() > 0.5 ? 1 : 0);
  }
  const index = parseInt(lines.map(l => l === 1 ? '1' : '0').join(''), 2);
  return hexagrams[index] || hexagrams[0];
};